import assert from "node:assert/strict";
import fs from "node:fs";
import { performance } from "node:perf_hooks";
import { compileCl2Activity } from "../core/Cl2Compiler.js";

const actionCount = 1600;
const nodes = {
  start: { id: "start", type: "flowStart", inputs: {}, next: { flowOut: { nodeId: "action0", port: "flowIn" } } },
};
for (let index = 0; index < actionCount; index += 1) {
  const id = `action${index}`;
  nodes[id] = {
    id,
    type: "setVariable",
    inputs: { key: id, value: index },
    next: { flowOut: { nodeId: index + 1 < actionCount ? `action${index + 1}` : "end", port: "flowIn" } },
  };
}
nodes.end = { id: "end", type: "activityEnd", inputs: {}, next: {} };
const blueprint = { startNodeId: "start", nodes, connections: [] };
const compilerSource = fs.readFileSync(new URL("../core/Cl2Compiler.js", import.meta.url), "utf8");
assert.doesNotMatch(
  compilerSource,
  /source\.slice\(0,\s*sourceOffset\)\.split\("\\n"\)/,
  "source-map line numbers must not rescan every generated-source prefix",
);

const compiledWarmup = compileCl2Activity(blueprint, { maxSteps: actionCount + 2 });
const sourceLines = compiledWarmup.source.split("\n");
for (const index of [0, 1, 17, 199, 799, 1599, 1600, 1601]) {
  const nodeId = index === 0 ? "start" : index === actionCount + 1 ? "end" : `action${index - 1}`;
  const mappedLine = compiledWarmup.debugInfo.sourceMap[nodeId].sourceLine;
  assert.match(sourceLines[mappedLine - 1], new RegExp(`case ${index}:`), `source map for ${nodeId} points at its generated case`);
}

const samples = [];
for (let sample = 0; sample < 5; sample += 1) {
  const before = performance.now();
  const compiled = compileCl2Activity(blueprint, { maxSteps: actionCount + 2 });
  samples.push(performance.now() - before);
  assert.equal(compiled.debugInfo.sourceMap.end.sourceLine, compiledWarmup.debugInfo.sourceMap.end.sourceLine);
}
samples.sort((a, b) => a - b);
console.log(`cl2-source-map-performance-probe: ${actionCount + 2} flow nodes, ${Buffer.byteLength(compiledWarmup.source)} generated bytes, median compile ${samples[2].toFixed(2)}ms (5 samples)`);
