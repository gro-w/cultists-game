import assert from "node:assert/strict";
import EventBus from "../core/EventBus.js";
import GameClock from "../core/GameClock.js";
import TimeService from "../core/TimeService.js";
import StateBoundaryService from "../core/StateBoundaryService.js";

const bus = new EventBus();
const clock = new GameClock(bus);
const time = new TimeService(clock, bus);
const state = { day: 1, phase: "day", duty: "on-duty", location: "work", energy: 100, mental: 100, physical: 100, satiety: 100 };
const service = new StateBoundaryService({ gameClock: clock, timeService: time, initialState: state, eventBus: bus, rules: { workStart: 480, workEnd: 960, wakeTime: 480 } });
service.sync();
assert.equal(service.snapshot().day, 1);
assert.equal(service.snapshot().phase, "night");
clock.restore({ day: 1, minutes: 960 });
service.state.duty = "on-duty";
service.toggleDuty();
assert.equal(clock.minutes, 960);
assert.equal(service.snapshot().duty, "off-duty");
clock.restore({ day: 1, minutes: 1380 });
const result = service.sleep();
assert.equal(result.clock.day, 2);
assert.equal(result.clock.minutes, 480);
assert.equal(service.snapshot().duty, "on-duty");
clock.restore({ day: 1, minutes: 500 });
service.state.duty = "on-duty";
time.consume(460, { source: "probe" });
assert.equal(service.snapshot().phase, "night");
console.log("phase-boundary probe: ok");
